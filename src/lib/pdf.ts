import { jsPDF } from 'jspdf';
import type { PurchaseOrder, QuotationRecord } from '../types';
import { formatDate, formatInr, formatOrderStatus } from './api';

export function downloadQuotationPdf(quote: QuotationRecord): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 48;
  let y = 56;

  // Header band
  doc.setFillColor(248, 243, 232);
  doc.rect(0, 0, 595, 112, 'F');
  doc.setTextColor(58, 35, 25);
  doc.setFont('times', 'bold');
  doc.setFontSize(26);
  doc.text('FOLKFORM', margin, y);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(120, 92, 74);
  doc.text('Where Culture Meets Commerce · Global Artisan Procurement Infrastructure', margin, y + 18);

  doc.setTextColor(176, 83, 48);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('COMMERCIAL QUOTATION', 595 - margin, y, { align: 'right' });
  doc.setTextColor(58, 35, 25);
  doc.setFont('courier', 'normal');
  doc.setFontSize(10);
  doc.text(quote.quoteCode, 595 - margin, y + 16, { align: 'right' });
  doc.text(`Issued: ${formatDate(quote.createdAt)}`, 595 - margin, y + 30, { align: 'right' });

  y = 142;

  if (quote.isDemo) {
    doc.setFillColor(233, 220, 199);
    doc.rect(margin, y - 14, 595 - margin * 2, 24, 'F');
    doc.setTextColor(58, 35, 25);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.text(
      'DEMONSTRATION QUOTATION — Seeded illustrative supplier record & commercial pricing for showcase evaluation.',
      margin + 10,
      y + 1,
    );
    y += 32;
  }

  // Supplier & RFQ details
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(120, 92, 74);
  doc.text('SUPPLIER / ARTISAN WORKSHOP', margin, y);
  doc.text('RFQ REFERENCE', 320, y);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(58, 35, 25);
  doc.text(quote.supplierName, margin, y + 16);
  doc.text(quote.rfqCode || quote.rfqId, 320, y + 16);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(
    `${quote.supplierCity || 'India'}, ${quote.supplierState || ''} · Verification: ${quote.supplierVerificationStatus || 'Pending'}`,
    margin,
    y + 31,
  );
  doc.text(quote.rfqTitle || 'Bulk Craft Procurement Request', 320, y + 31, { maxWidth: 225 });

  y += 66;
  doc.setDrawColor(233, 220, 199);
  doc.line(margin, y, 595 - margin, y);
  y += 24;

  // Pricing table
  doc.setFillColor(58, 35, 25);
  doc.rect(margin, y - 14, 595 - margin * 2, 24, 'F');
  doc.setTextColor(255, 252, 246);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('DESCRIPTION', margin + 10, y + 1);
  doc.text('QTY', 330, y + 1, { align: 'right' });
  doc.text('UNIT RATE', 430, y + 1, { align: 'right' });
  doc.text('TOTAL (INR)', 595 - margin - 10, y + 1, { align: 'right' });

  y += 28;
  doc.setTextColor(58, 35, 25);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(quote.rfqTitle || 'Custom Artisan Production Batch', margin + 10, y, { maxWidth: 250 });
  doc.text(String(quote.rfqQuantity ?? quote.moq), 330, y, { align: 'right' });
  doc.text(formatInr(quote.unitPriceInr), 430, y, { align: 'right' });
  doc.text(formatInr(quote.totalProductCostInr), 595 - margin - 10, y, { align: 'right' });

  y += 28;
  doc.text('Estimated Freight / Packing & Logistics', margin + 10, y);
  doc.text(formatInr(quote.shippingEstimateInr), 595 - margin - 10, y, { align: 'right' });

  y += 20;
  doc.line(320, y, 595 - margin, y);
  y += 20;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Estimated Landed Total', 320, y);
  doc.setTextColor(176, 83, 48);
  doc.text(formatInr(quote.totalLandedCostInr), 595 - margin - 10, y, { align: 'right' });

  y += 42;
  doc.setTextColor(58, 35, 25);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('Commercial & Production Terms', margin, y);
  y += 18;

  const terms = [
    `Minimum Order Quantity (MOQ): ${quote.moq} units`,
    `Declared Workshop Capacity: ${quote.availableCapacity} units/month (supplier self-declared)`,
    `Estimated Production Lead Time: ${quote.estimatedProductionDays} calendar days`,
    `Quotation Validity: ${quote.validityDays} days from issue date`,
    `Customisation Notes: ${quote.customisationNotes || 'Standard craft specification'}`,
    `Commercial Conditions: ${quote.conditions || 'Standard Folkform B2B terms'}`,
  ];

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  for (const line of terms) {
    const wrapped = doc.splitTextToSize(`• ${line}`, 595 - margin * 2);
    doc.text(wrapped, margin, y);
    y += wrapped.length * 14 + 4;
  }

  // Footer
  doc.setDrawColor(233, 220, 199);
  doc.line(margin, 775, 595 - margin, 775);
  doc.setFontSize(8.5);
  doc.setTextColor(120, 92, 74);
  doc.text(
    'Generated by Folkform Procurement OS · Explicit human buyer approval is required before converting any quotation to a Purchase Order.',
    margin,
    792,
  );

  doc.save(`${quote.quoteCode}_Folkform_Quotation.pdf`);
}

export function downloadPurchaseOrderPdf(order: PurchaseOrder): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 48;
  let y = 56;

  doc.setFillColor(58, 35, 25);
  doc.rect(0, 0, 595, 114, 'F');
  doc.setTextColor(255, 252, 246);
  doc.setFont('times', 'bold');
  doc.setFontSize(26);
  doc.text('FOLKFORM', margin, y);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(233, 220, 199);
  doc.text('Where Culture Meets Commerce · B2B Purchase Order Document', margin, y + 18);

  doc.setTextColor(190, 151, 83);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.text('PURCHASE ORDER', 595 - margin, y, { align: 'right' });
  doc.setTextColor(255, 252, 246);
  doc.setFont('courier', 'normal');
  doc.setFontSize(10);
  doc.text(order.poNumber, 595 - margin, y + 16, { align: 'right' });
  doc.text(`Status: ${formatOrderStatus(order.status)}`, 595 - margin, y + 30, { align: 'right' });

  y = 144;
  if (order.isDemo) {
    doc.setFillColor(248, 243, 232);
    doc.rect(margin, y - 14, 595 - margin * 2, 24, 'F');
    doc.setTextColor(58, 35, 25);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8.5);
    doc.text(
      'DEMONSTRATION PURCHASE ORDER — Simulated escrow settlement; not a live legal or payment transfer.',
      margin + 10,
      y + 1,
    );
    y += 32;
  }

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(120, 92, 74);
  doc.text('BUYER / PROCURING ENTITY', margin, y);
  doc.text('SUPPLIER / ARTISAN PARTNER', 315, y);

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.setTextColor(58, 35, 25);
  doc.text(order.buyerCompany, margin, y + 16);
  doc.text(order.supplierName, 315, y + 16);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.text(`Contact: ${order.buyerName}`, margin, y + 31);
  doc.text(`Deliver To: ${order.deliveryLocation}`, margin, y + 45, { maxWidth: 230 });
  doc.text(`Origin: ${order.supplierLocation || 'India Craft Cluster'}`, 315, y + 31);
  doc.text(`Expected Delivery: ${formatDate(order.expectedDeliveryDate)}`, 315, y + 45);

  y += 82;
  doc.setFillColor(233, 220, 199);
  doc.rect(margin, y - 14, 595 - margin * 2, 24, 'F');
  doc.setTextColor(58, 35, 25);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text('LINE ITEM', margin + 10, y + 1);
  doc.text('QTY', 330, y + 1, { align: 'right' });
  doc.text('UNIT RATE', 430, y + 1, { align: 'right' });
  doc.text('AMOUNT (INR)', 595 - margin - 10, y + 1, { align: 'right' });

  y += 28;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text(order.title, margin + 10, y, { maxWidth: 255 });
  doc.text(String(order.quantity), 330, y, { align: 'right' });
  doc.text(formatInr(order.unitPriceInr), 430, y, { align: 'right' });
  doc.text(formatInr(order.subtotalInr), 595 - margin - 10, y, { align: 'right' });

  y += 32;
  doc.text('Logistics & Export/Domestic Freight Estimate', margin + 10, y);
  doc.text(formatInr(order.shippingInr), 595 - margin - 10, y, { align: 'right' });

  y += 18;
  doc.setDrawColor(233, 220, 199);
  doc.line(310, y, 595 - margin, y);
  y += 20;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11.5);
  doc.text('Grand Total (INR)', 310, y);
  doc.setTextColor(176, 83, 48);
  doc.text(formatInr(order.totalAmountInr), 595 - margin - 10, y, { align: 'right' });

  y += 36;
  doc.setTextColor(58, 35, 25);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('Approval & Settlement Audit', margin, y);
  y += 18;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  const auditLines = [
    `Buyer Explicit Approval: ${order.buyerApprovedAt ? formatDate(order.buyerApprovedAt) : 'Pending buyer approval'}`,
    `Supplier Order Confirmation: ${order.supplierConfirmedAt ? formatDate(order.supplierConfirmedAt) : 'Awaiting supplier confirmation'}`,
    `Settlement Status: ${order.paymentStatus.replace(/_/g, ' ')} (${order.paymentAdapterNote || 'Simulated Adapter'})`,
    `Platform Commission Assumption: ${Math.round(order.commissionRate * 100)}% on product GMV (${formatInr(order.platformCommissionInr)}, realised only upon completion)`,
  ];
  for (const l of auditLines) {
    doc.text(`• ${l}`, margin, y);
    y += 16;
  }

  if (order.milestones && order.milestones.length > 0) {
    y += 14;
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.text('Recorded Production Milestones', margin, y);
    y += 18;
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9);
    for (const m of order.milestones.slice(0, 7)) {
      const text = `${formatDate(m.createdAt)} — ${formatOrderStatus(m.stage)}: ${m.notes}`;
      const wrapped = doc.splitTextToSize(text, 595 - margin * 2);
      doc.text(wrapped, margin, y);
      y += wrapped.length * 13 + 4;
    }
  }

  doc.setDrawColor(233, 220, 199);
  doc.line(margin, 775, 595 - margin, 775);
  doc.setFontSize(8.5);
  doc.setTextColor(120, 92, 74);
  doc.text('Folkform · AI-Powered Global Artisan Commerce & Procurement Infrastructure', margin, 792);

  doc.save(`${order.poNumber}_Folkform_PurchaseOrder.pdf`);
}
